-- misc/mermaid-width.lua
-- Render mermaid diagrams at high resolution, then size them RELATIVE to their
-- container so they fit both standalone and inside layout panels.

local mermaid_render_width = 10  -- render resolution (inches) to avoid clipping

function CodeBlock(el)
  if el.classes:includes("mermaid") then
    -- Set a good default render resolution if the author did not specify one.
    if not el.attributes["fig-width"] then
      if quarto.doc.is_format("pdf") or quarto.doc.is_format("latex") then
        el.attributes["fig-width"] = tostring(mermaid_render_width)
      else
        el.attributes["fig-width"] = "8"  -- default for HTML
      end
    end
  end
  return el
end

function Image(el)
  -- Match images generated by Mermaid.
  if el.src:match("mermaid%-figure") then
    el.attributes["height"] = nil            -- never stretch vertically
    el.attributes["keepaspectratio"] = "true"
    el.attributes["fig-align"] = "center"

    -- Use a relative width (100% -> \linewidth in LaTeX) so the diagram fills
    -- its container: the full text block when standalone, or the panel width
    -- when inside a layout (e.g. layout-ncol=2). An absolute inch width would
    -- overflow the narrow minipages Quarto generates for layout panels.
    el.attributes["width"] = "100%"
  end
  return el
end
